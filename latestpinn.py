def generate_data(t_array, y0, beta, q, rho, xi, gamma):
  n_steps = len(t_array)
  states = np.zeros((n_steps, len(y0)))
  states[0] = y0

  for n in range(n_steps - 1):
    A, R, I, S = states[n]

    # Discrete update equations
    A_next = (
        A
        + 0.1 * (
            xi - gamma*A
        )
    )
    R_next = (
        R
        + 0.1 * (
            -q*A*R + beta*S
        )
    )
    I_next = (
        I
        + 0.1 * (
            q*A*R - rho*I
        )
    )
    S_next = (
        S
        + 0.1 * (
            rho*I - beta*S
        )
    )
    states[n+1] = [
        A_next,
        R_next,
        I_next,
        S_next,
    ]
  return states

