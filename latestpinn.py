def dinn(data_t, data_y, noise_level, variable_filename="variables.dat"):
    init_val = -2.197
    beta_raw = dde.Variable(init_val)
    q_raw = dde.Variable(init_val)
    rho_raw = dde.Variable(init_val)
    xi_raw = dde.Variable(init_val)
    gamma_raw = dde.Variable(init_val)

    variable_list = [
        beta_raw,
        q_raw,
        rho_raw,
        xi_raw,
        gamma_raw,
    ]


    def discrete_residual(t, y_pred):

        beta = tf.math.sigmoid(beta_raw)
        q = tf.math.sigmoid(q_raw)
        rho = tf.math.sigmoid(rho_raw)
        xi = tf.math.sigmoid(xi_raw)
        gamma = tf.math.sigmoid(gamma_raw)


        A_pred = y_pred[:, 0:1]
        R_pred = y_pred[:, 1:2]
        I_pred = y_pred[:, 2:3]
        S_pred = y_pred[:, 3:4]


        A_now  = A_pred[:-1]
        R_now  = R_pred[:-1]
        I_now  = I_pred[:-1]
        S_now  = S_pred[:-1]


        A_next = A_pred[1:]
        R_next = R_pred[1:]
        I_next = I_pred[1:]
        S_next = S_pred[1:]


        A_model = A_now + 0.1*(xi - gamma*A_now)
        R_model = R_now + 0.1*(-q*R_now*A_now + beta*S_now)
        I_model = I_now + 0.1*(q*R_now*A_now - rho*I_now)
        S_model = S_now + 0.1*(-beta*S_now + rho*I_now)


        r_A = A_next - A_model
        r_R = R_next - R_model
        r_I = I_next - I_model
        r_S = S_next - S_model


        return [
            r_A,
            r_R,
            r_I,
            r_S
        ]

    geom = dde.geometry.TimeDomain(data_t[0,0], data_t[-1,0])

    y_noise = data_y + np.random.normal(loc=0, scale=data_y.std(axis=0), size=data_y.shape) * noise_level

    observe_A = dde.icbc.PointSetBC(
        data_t,
        y_noise[:,0:1],
        component=0
    )

    observe_R = dde.icbc.PointSetBC(
        data_t,
        y_noise[:, 1:2],
        component = 1
    )

    observe_I = dde.icbc.PointSetBC(
        data_t,
        y_noise[:, 2:3],
        component = 2
    )

    observe_S = dde.icbc.PointSetBC(
        data_t,
        y_noise[:, 3:4],
        component = 3
    )

    data = dde.data.PDE(
    geom,
    discrete_residual,
    [
        observe_A,
        observe_R,
        observe_I,
        observe_S,
    ],
    num_domain=0,
    num_boundary=0,
    anchors=data_t,
)

    net = dde.nn.FNN([1] + [neurons] * layers + [4], activation, "Glorot normal")

    def feature_transform(t):
        t = t / data_t[-1,0]
        return t

    net.apply_feature_transform(feature_transform)

    # Instantiate the model after defining data and net
    model = dde.Model(data, net)

    model.compile(
    "adam",
    lr=1e-3,
    loss_weights=8*[1],
    external_trainable_variables=variable_list
)

    variable = dde.callbacks.VariableValue(
        variable_list,
        period=5000,
        filename=variable_filename,
        precision=8
    )

    model.train(
    iterations=30000,
    callbacks=[variable]
)

    return model, variable

