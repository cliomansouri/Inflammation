import re
import numpy as np
import pandas as pd
from scipy.special import expit


parameters_real = {
    "beta": 0.001,
    "q": 0.55,
    "rho": 0.1,
    "xi": 0.004,
    "gamma": 0.008,
}

parameter_names = [
    "beta",
    "q",
    "rho",
    "xi",
    "gamma",
]

noise_levels = [0.01, 0.05, 0.10, 0.20]

results = []

for noise_level in noise_levels:

    filename = (
        f"variables_{int(noise_level * 100)}percent.dat"
    )

    with open(filename, "r") as f:
        lines = f.readlines()

    if not lines:
        raise ValueError(f"{filename} is empty")

    # Final training checkpoint
    last_line = lines[-1]

    matches = re.findall(r"\[(.*?)\]", last_line)

    if not matches:
        raise ValueError(
            f"Could not parse parameter values from {filename}"
        )

    raw_values = np.fromstring(
        min(matches, key=len),
        sep=","
    )

    if len(raw_values) != len(parameter_names):
        raise ValueError(
            f"Expected {len(parameter_names)} parameters "
            f"in {filename}, found {len(raw_values)}"
        )

    predicted_values = expit(raw_values)

    for name, predicted in zip(
        parameter_names,
        predicted_values
    ):
        actual = parameters_real[name]

        results.append({
            "noise_percent": noise_level * 100,
            "parameter": name,
            "actual": actual,
            "predicted": predicted,
            "error_percent":
                abs(predicted - actual) / actual * 100,
        })


results_df = pd.DataFrame(results)

print(
    results_df.to_string(
        index=False,
        float_format=lambda x: f"{x:.6f}"
    )
)